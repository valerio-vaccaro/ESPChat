#!/usr/bin/env python3
"""Minimal TTF -> LVGL 8 font converter (4 bpp, plain bitmaps), so the build needs no npm tools.
usage: gen_font.py <font.ttf> <px> <name> <fallback-symbol|NULL> <out.c>"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, px, name, fallback, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
font = ImageFont.truetype(ttf, px)
ascent, descent = font.getmetrics()

ranges = [(0x20, 0x7E), (0xA0, 0xFF)]
extras = [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC, 0x2190, 0x2191, 0x2192, 0x2193,
          0x2500, 0x2502, 0x2588, 0x2591, 0x2592, 0x2593, 0x25B6, 0x25CF]
codes = [c for a, b in ranges for c in range(a, b + 1)] + extras

bitmap = bytearray()
dscs = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0 */"]
for cp in codes:
    ch = chr(cp)
    adv = int(round(font.getlength(ch) * 16))
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    idx = len(bitmap)
    if w and h:
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        nib = [v >> 4 for v in im.tobytes()]
        if len(nib) % 2: nib.append(0)
        bitmap += bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    dscs.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, .ofs_x = {x0}, .ofs_y = {-y1}}} /* U+{cp:04X} */")

n1 = ranges[0][1] - ranges[0][0] + 1
n2 = ranges[1][1] - ranges[1][0] + 1
ex_ofs = ", ".join(f"0x{c - extras[0]:x}" for c in extras)
fb = f"&{fallback}" if fallback != "NULL" else "NULL"
hexes = ",".join(f"0x{b:02x}" for b in bitmap)
src = f"""/* Generated by tools/fonts/gen_font.py from {ttf.split('/')[-1]} at {px}px, 4 bpp. Do not edit. */
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{{hexes}}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(','+chr(10)).join(dscs)}
}};

static const uint16_t extra_list[] = {{{ex_ofs}}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {ranges[0][0]}, .range_length = {n1}, .glyph_id_start = 1, .unicode_list = NULL,
     .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},
    {{.range_start = {ranges[1][0]}, .range_length = {n2}, .glyph_id_start = {1 + n1}, .unicode_list = NULL,
     .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},
    {{.range_start = {extras[0]}, .range_length = {extras[-1] - extras[0] + 1}, .glyph_id_start = {1 + n1 + n2},
     .unicode_list = extra_list, .glyph_id_ofs_list = NULL, .list_length = {len(extras)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},
}};

static lv_font_fmt_txt_glyph_cache_t cache;
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL, .kern_scale = 0,
    .cmap_num = 3, .bpp = 4, .kern_classes = 0, .bitmap_format = 0, .cache = &cache}};

{'extern const lv_font_t ' + fallback + ';' if fallback != 'NULL' else ''}
const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent}, .base_line = {descent}, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2, .underline_thickness = 1, .dsc = &font_dsc, .fallback = {fb}, .user_data = NULL}};
"""
open(out, "w").write(src)
print(f"{name}: {len(codes)} glyphs, {len(bitmap)} bytes bitmap, line height {ascent + descent}")
